export type Dict = (typeof dict)["pt"];
export const getDict = (lang: Lang): Dict => dict[lang] as unknown as Dict;

export function detectLang(): Lang {
  try {
    const saved = localStorage.getItem("pc.lang");
    if (saved === "pt" || saved === "en") return saved;
  } catch {
    /* storage unavailable */
  }
  return typeof navigator !== "undefined" && navigator.language.toLowerCase().startsWith("pt")
    ? "pt"
    : "en";
}
